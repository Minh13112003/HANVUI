export interface Say {
  who: string;
  zh: string;
}
export type Question =
  | { type: 'judge'; script: Say[]; statement: string; answer: 0 | 1 } // 0 = đúng, 1 = sai
  | { type: 'choice'; script?: Say[]; prompt: string; options: string[]; answer: number }
  | { type: 'order'; words: string[]; answer: string[] }; // nhiều thứ tự đúng thì liệt kê hết

export interface ExamDef {
  level: number;
  idx: number;
  title: string;
  durationMin: number;
  listening: Question[];
  reading: Question[];
  writing: Question[];
}

const J = (zh: string, statement: string, ok: boolean): Question => ({ type: 'judge', script: [{ who: 'A', zh }], statement, answer: ok ? 0 : 1 });
const C = (a: string, b: string, prompt: string, options: [string, string, string], answer: number): Question => ({
  type: 'choice', script: [{ who: 'A', zh: a }, { who: 'B', zh: b }], prompt, options, answer,
});
const R = (prompt: string, options: [string, string, string], answer: number): Question => ({ type: 'choice', prompt, options, answer });
const O = (words: string[], ...answer: string[]): Question => ({ type: 'order', words, answer });

