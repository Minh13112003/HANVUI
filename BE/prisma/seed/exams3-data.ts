const C = (a: string, b: string, prompt: string, options: [string, string, string], answer: number): Question => ({
  type: 'choice', script: [{ who: 'A', zh: a }, { who: 'B', zh: b }], prompt, options, answer,
});
const D = (script: [string, string][], prompt: string, options: [string, string, string], answer: number): Question => ({
  type: 'choice', script: script.map(([who, zh]): Say => ({ who, zh })), prompt, options, answer,
});
const R = (prompt: string, options: [string, string, string], answer: number): Question => ({ type: 'choice', prompt, options, answer });
const O = (words: string[], ...answer: string[]): Question => ({ type: 'order', words, answer });

